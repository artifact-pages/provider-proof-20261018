import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const size = process.argv[2];
if (!["small", "large"].includes(size ?? "")) {
  throw new Error("Usage: node scripts/generate-a9-fixtures.mjs small|large");
}

const repoRoot = resolve(new URL("..", import.meta.url).pathname);
const sourceDir = join(repoRoot, "sites", "a", ".a9-generated");
const sourceMarker = join(sourceDir, ".provider-proof-generated-fixture");
const outputDir = join(repoRoot, ".local", "a9-generated", size);
const outputMarker = join(outputDir, ".provider-proof-generated-fixture");
const counts = size === "large"
  ? { headings: 40_000, manifestPaths: 50_000 }
  : { headings: 12, manifestPaths: 8 };
const headingPadding = size === "large" ? "x".repeat(140) : "small";
const sourcePath = join(sourceDir, "a9-index-size-fixture.md");

function resetOwnedDirectory(directory, markerPath) {
  if (existsSync(directory)) {
    if (!existsSync(markerPath) || readFileSync(markerPath, "utf8").trim() !== "generated by scripts/generate-a9-fixtures.mjs") {
      throw new Error(`Refusing to replace an unmarked directory: ${directory}`);
    }
    rmSync(directory, { recursive: true, force: true });
  }
  mkdirSync(directory, { recursive: true });
  writeFileSync(markerPath, "generated by scripts/generate-a9-fixtures.mjs\n");
}

resetOwnedDirectory(sourceDir, sourceMarker);
resetOwnedDirectory(outputDir, outputMarker);

const sourceLines = [
  "# Synthetic A9 index-size fixture",
  "",
  "This ignored file exercises generated index size without creating thousands of source artifacts.",
  "",
];
for (let index = 0; index < counts.headings; index += 1) {
  sourceLines.push(`## A9 heading ${String(index).padStart(5, "0")} ${headingPadding}`);
}
writeFileSync(sourcePath, `${sourceLines.join("\n")}\n`);

const artifactCount = size === "large" ? 40_000 : 12;
const artifacts = Array.from({ length: artifactCount }, (_, index) => {
  const path = `synthetic/${String(index).padStart(5, "0")}-${"p".repeat(size === "large" ? 160 : 12)}.md`;
  return {
    id: path,
    title: `Synthetic A9 artifact ${String(index).padStart(5, "0")}`,
    path,
    format: "markdown",
    filename: path.split("/").at(-1),
    artifactUrl: `/_artifacts/proof-a-20261018/${path}`,
    updatedAt: "2026-10-20T00:00:00Z",
    lastCommitter: { name: "Synthetic A9 fixture" },
    lastAuthor: { name: "Synthetic A9 fixture", commitSha: "a".repeat(40) },
    source: {
      repository: "artifact-pages/provider-proof-20261018",
      repositoryUrl: "https://github.com/artifact-pages/provider-proof-20261018",
      ref: "main",
      filePath: `sites/a/${path}`,
    },
    toc: [],
  };
});
const syntheticIndex = {
  schemaVersion: 1,
  site: { id: "proof-a-20261018", title: "Synthetic A9 fixture" },
  generatedAt: "2026-10-20T00:00:00Z",
  artifacts,
};
const manifestPaths = Array.from({ length: counts.manifestPaths }, (_, index) =>
  `synthetic/${String(index).padStart(5, "0")}-${"m".repeat(size === "large" ? 180 : 8)}.md`,
);
const syntheticSearchManifest = {
  generation: `synthetic-a9-${size}-20261020`,
  version: 1,
  site: "proof-a-20261018",
  documents: manifestPaths.length,
  root: { url: "/_indexes/proof-a-20261018/search/root", sha256: "0".repeat(64), bytes: 0, rawBytes: 0 },
  shards: Array.from({ length: 128 }, () => null),
  snippetLimits: {
    maxDocumentBytes: 262144,
    maxSiteBytes: 33554432,
    truncatedDocuments: manifestPaths,
    omittedDocuments: [],
  },
};

const files = [
  ["synthetic-index.json", Buffer.from(JSON.stringify(syntheticIndex))],
  ["synthetic-search-manifest.json", Buffer.from(JSON.stringify(syntheticSearchManifest))],
];
for (const [filename, bytes] of files) {
  const path = join(outputDir, filename);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, bytes);
}

const summary = {
  fixture: "synthetic; not builder output and not live-provider evidence",
  size,
  source: { path: "sites/a/.a9-generated/a9-index-size-fixture.md", bytes: Buffer.byteLength(sourceLines.join("\n")) + 1 },
  objects: Object.fromEntries(files.map(([filename, bytes]) => [filename, {
    bytes: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  }])),
};
if (size === "large" && files.some(([, bytes]) => bytes.length <= 10_000_000)) {
  throw new Error("Large synthetic object fixtures must each exceed 10,000,000 decoded bytes");
}
if (size === "small" && files.some(([, bytes]) => bytes.length >= 10_000_000)) {
  throw new Error("Small synthetic object fixtures must stay below 10,000,000 decoded bytes");
}

writeFileSync(join(outputDir, "summary.json"), `${JSON.stringify(summary, null, 2)}\n`);
console.log(JSON.stringify(summary, null, 2));
